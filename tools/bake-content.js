#!/usr/bin/env node
/*
 * bake-content.js - compiles sets/ into the single runtime artifact,
 * game-content.js. Run: node tools/bake-content.js
 *
 * The runtime never fetches (file:// has no fetch), so content ships as a
 * classic script exposing `Content` on the browser global, UMD-wrapped like
 * game-core.js so Node tools can require() it too.
 *
 * Refuses to bake unless the full gate chain is green: it runs
 * tools/validate-sets.js (M1-M16, which itself verifies the gloss-audit stamp
 * and the uniqueness verdicts) and aborts on any hard failure. There is no
 * flag to skip this.
 */
'use strict';
var fs = require('fs');
var path = require('path');
var crypto = require('crypto');
var execFileSync = require('child_process').execFileSync;

var ROOT = path.join(__dirname, '..');

// Gate first. validate-sets exits non-zero on any hard failure and that
// failure propagates out of this script - an ungated bake must be impossible.
execFileSync(process.execPath, [path.join(__dirname, 'validate-sets.js')], { stdio: 'inherit' });

var files = [];
['A', 'B', 'C'].forEach(function (bank) {
  var dir = path.join(ROOT, 'sets', bank);
  if (!fs.existsSync(dir)) return;
  fs.readdirSync(dir).filter(function (f) { return /\.json$/.test(f); }).sort().forEach(function (f) {
    files.push(path.join(dir, f));
  });
});

var manifest = crypto.createHash('sha256');
var sets = files.map(function (f) {
  var raw = fs.readFileSync(f);
  manifest.update(crypto.createHash('sha256').update(raw).digest('hex'));
  return JSON.parse(raw);
});
// authoring-only fields never ship to the runtime
sets.forEach(function (s) { delete s.drafting_notes; });
sets.sort(function (a, b) { return (a.band - b.band) || (a.id < b.id ? -1 : 1); });

var bands = {};
var counts = { sets: sets.length, words: 0, sentences: 0, contrasts: 0 };
var perBank = { A: 0, B: 0, C: 0 };
sets.forEach(function (s) {
  (bands[s.band] = bands[s.band] || []).push(s.id);
  counts.words += s.words.length;
  counts.sentences += s.sentences.length;
  counts.contrasts += s.contrasts.length;
  perBank[s.bank] += 1;
});

var data = {
  schema_version: 1,
  built_at: new Date().toISOString().replace(/\.\d+Z$/, 'Z'),
  builder: 'tools/bake-content.js',
  source_sha256: manifest.digest('hex'),
  counts: counts,
  bands: bands,
  sets: sets
};

var js = [
  '/*',
  ' * game-content.js - BAKED corpus for Word Vault. DO NOT EDIT BY HAND.',
  ' * Generated by tools/bake-content.js from sets/**.json, which are the',
  ' * source of truth; every set passed gates G1-G9 and M1-M16 before baking.',
  ' *',
  ' * UMD-style: exposes `Content` on the browser global, and module.exports',
  ' * under node so the tools can require() it. Classic script so it loads',
  ' * from file:// with no server.',
  ' */',
  '(function (root, factory) {',
  '  if (typeof module !== \'undefined\' && module.exports) module.exports = factory();',
  '  else root.Content = factory();',
  '})(typeof self !== \'undefined\' ? self : this, function () {',
  '  \'use strict\';',
  '  var DATA = ' + JSON.stringify(data, null, 1).replace(/\n/g, '\n  ') + ';',
  '  function byId(id) {',
  '    for (var i = 0; i < DATA.sets.length; i++) if (DATA.sets[i].id === id) return DATA.sets[i];',
  '    return null;',
  '  }',
  '  return { SCHEMA_VERSION: DATA.schema_version, data: DATA, sets: DATA.sets, byId: byId };',
  '});',
  ''
].join('\n');
fs.writeFileSync(path.join(ROOT, 'game-content.js'), js);

var pct = function (n) { return counts.sets ? Math.round(100 * n / counts.sets) + '%' : '-'; };
var report = [
  '# Content report',
  '',
  'Generated by tools/bake-content.js at ' + data.built_at + '. Source sha256 ' + data.source_sha256.slice(0, 12) + '…',
  '',
  '| | count |',
  '|---|---|',
  '| sets | ' + counts.sets + ' |',
  '| words | ' + counts.words + ' |',
  '| sentences | ' + counts.sentences + ' |',
  '| contrast lines | ' + counts.contrasts + ' |',
  '',
  'Bank mix vs the 65/20/15 starting targets: A ' + perBank.A + ' (' + pct(perBank.A) + '), B ' +
    perBank.B + ' (' + pct(perBank.B) + '), C ' + perBank.C + ' (' + pct(perBank.C) + ').',
  '',
  'Sets per band: ' + Object.keys(bands).sort().map(function (b) {
    return b + ': ' + bands[b].length;
  }).join(', ') + '.',
  ''
].join('\n');
fs.writeFileSync(path.join(ROOT, 'reference', 'CONTENT-REPORT.md'), report);

console.log('bake-content: ' + counts.sets + ' set(s), ' + counts.sentences + ' sentences -> game-content.js (' +
  Math.round(js.length / 1024) + ' KB)');
